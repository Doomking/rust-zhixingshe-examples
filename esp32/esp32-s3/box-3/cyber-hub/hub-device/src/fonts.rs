pub fn draw_icon<D>(display: &mut D, name: &str, point: Point, color: Rgb565) -> Result<(), D::Error>
where
    D: DrawTarget<Color = Rgb565>,
{
    if let Some(c) = CHINESE_CHARS.iter().find(|c| c.name == name) {
        for y in 0..16 {
            let row_idx = y * 2;
            for x_byte in 0..2 {
                let byte = c.bitmap[row_idx + x_byte];
                for x_bit in 0..8 {
                    if (byte & (0x80 >> x_bit)) != 0 {
                        display.draw_iter(core::iter::once(Pixel(
                            point + Point::new((x_byte * 8 + x_bit) as i32, y as i32),
                            color,
                        )))?;
                    }
                }
            }
        }
    }
    Ok(())
}

pub fn draw_chinese_char<D>(display: &mut D, name: &str, point: Point, color: Rgb565) -> Result<(), D::Error>
where
    D: DrawTarget<Color = Rgb565>,
{
    draw_icon(display, name, point, color)
}

pub fn draw_chinese_string<D>(display: &mut D, text: &str, mut point: Point, color: Rgb565) -> Result<(), D::Error>
where
    D: DrawTarget<Color = Rgb565>,
{
    for c in text.chars() {
        let mut buf = [0u8; 4];
        let s = c.encode_utf8(&mut buf);
        draw_chinese_char(display, s, point, color)?;
        point += Point::new(18, 0); 
    }
    Ok(())
}
